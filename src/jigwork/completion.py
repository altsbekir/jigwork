"""Shell completions generated from the CLI's own parser, so they never go stale.

`jigw completion fish > ~/.config/fish/completions/jigw.fish`. Descriptions are in the
language active when the script is generated.
"""

from __future__ import annotations

import argparse

from jigwork import COMMAND, NAME


def _subcommands(parser: argparse.ArgumentParser) -> list[tuple[str, str, argparse.ArgumentParser]]:
    for action in parser._actions:
        if isinstance(action, argparse._SubParsersAction):
            helps = {a.dest: a.help or "" for a in action._choices_actions}
            return [(name, helps.get(name, ""), sub) for name, sub in action.choices.items()]
    return []


def _quote(text: str) -> str:
    return "'" + text.replace("\\", "\\\\").replace("'", "\\'") + "'"


def _options(prog: str, condition: str, parser: argparse.ArgumentParser) -> list[str]:
    lines = []
    for action in parser._actions:
        if isinstance(action, argparse._SubParsersAction):
            continue
        help_text = _quote(action.help or "")
        if action.option_strings:
            flags = []
            for opt in action.option_strings:
                flags += ["-l", opt[2:]] if opt.startswith("--") else ["-s", opt[1:]]
            values = f" -xa {_quote(' '.join(action.choices))}" if action.choices else ""
            lines.append(
                f"complete -c {prog} -n {condition} {' '.join(flags)}{values} -d {help_text}"
            )
        elif action.choices:
            values = _quote(" ".join(action.choices))
            lines.append(f"complete -c {prog} -n {condition} -xa {values} -d {help_text}")
        elif action.nargs != argparse.REMAINDER and action.dest in ("path", "folder"):
            lines.append(f"complete -c {prog} -n {condition} -F")
    return lines


def fish(parser: argparse.ArgumentParser) -> str:
    out = [f"# {NAME} completions for fish (generated by `{COMMAND} completion fish`)"]
    for prog in (COMMAND, NAME):
        out.append(f"complete -c {prog} -f")
        top = _subcommands(parser)
        names = " ".join(name for name, _, _ in top)
        out.append(f"complete -c {prog} -n __fish_use_subcommand -l help -s h -d {_quote('help')}")
        for name, help_text, sub in top:
            out.append(
                f"complete -c {prog} -n __fish_use_subcommand -a {name} -d {_quote(help_text)}"
            )
            seen = f"'__fish_seen_subcommand_from {name}'"
            nested = _subcommands(sub)
            if nested:
                nested_names = " ".join(n for n, _, _ in nested)
                inside = f"__fish_seen_subcommand_from {name}"
                not_yet = f"'{inside}; and not __fish_seen_subcommand_from {nested_names}'"
                for child, child_help, child_parser in nested:
                    out.append(
                        f"complete -c {prog} -n {not_yet} -a {child} -d {_quote(child_help)}"
                    )
                    cond = f"'{inside}; and __fish_seen_subcommand_from {child}'"
                    out += _options(prog, cond, child_parser)
            else:
                out += _options(prog, seen, sub)
        out.append(f"# top-level: {names}")
    return "\n".join(out) + "\n"
